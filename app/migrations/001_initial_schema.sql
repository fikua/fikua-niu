-- PostgreSQL schema (the platform cluster, schema "niu"). Replaces the SQLite
-- migrations 001-005 one for one; the old SQLite data is copied in by
-- cmd/sqlite2pg after these have run.
-- +goose Up
CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL UNIQUE,
  display_name  TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  avatar_emoji  TEXT NOT NULL DEFAULT '🐦',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sessions (
  token_hash  TEXT PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE items (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT NOT NULL,
  name_normalized  TEXT NOT NULL,
  location         TEXT NOT NULL CHECK (location IN ('shopping','pantry')),
  position         DOUBLE PRECISION NOT NULL,
  added_by         BIGINT REFERENCES users(id),
  moved_by         BIGINT REFERENCES users(id),
  moved_at         TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- EC-06: unicitat sobre el nom normalitzat (retallat + minúscules
-- Unicode-aware, calculat a Go — vegeu ADR-02), a través de totes dues
-- caixes (per això NO inclou `location` a l'índex).
CREATE UNIQUE INDEX idx_items_name_normalized ON items(name_normalized);

CREATE TABLE events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT REFERENCES users(id),
  kind       TEXT NOT NULL,
  payload    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

